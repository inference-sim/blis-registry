#!/usr/bin/env python3
"""Write routing/servingstudio-dsv41-flash.yaml from derive_routing_profiles.py's output.

    emit_routing_profiles.py <derived.json> [--check]

The derived JSON is produced from UW-SyFI/servingstudio-workload's DeepSeek-V4.1-Flash
capture by derive_routing_profiles.py, which this script does not re-run: the capture is
third-party data that is read where it was downloaded and never vendored. So the drift gate
runs where the capture is present, as the AISimulate writers' `--check` does in rederive.

Only FIT values are written (requests 0-39); the HELD agreement is checked here and stated in
each profile's rationale, and a curve that fails it is not written. The set's role is
`sensitivity`: the capture is a tier-2 source, and no tier-1 source measures DeepSeek-V4.1's
per-rank routed load, so it is applied only when a scenario names it.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TARGET = REPO / "routing" / "servingstudio-dsv41-flash.yaml"
SET_NAME = "servingstudio-dsv41-flash"
SOURCE = ("https://huggingface.co/datasets/UW-SyFI/servingstudio-workload@"
          "b4b749dc7f3fe4a8f2db45b76cfbabdba59515e0 deepseek_v41_flash/vllm/diverse_100/"
          "capture/20260924 (routes.u16 sha256 2a166b82..., per its provenance.json)")
ENGINE = "vLLM fork 892da0822 (0.1.dev21920), TP4 EP4, EPLB rearrange off"
CATEGORY = "text"
# The pre-registered held-out tolerance (ROUTING.md section 0): a curve ships only if every
# point's FIT median is within 10% of the HELD median.
MAX_HELD_ERR = 0.10


def held_err(fit: dict, held: dict, q: str) -> float:
    errs = [abs(fit[k][f"{q}_median"] - held[k][f"{q}_median"]) / held[k][f"{q}_median"]
            for k in fit if k in held]
    return max(errs) if errs else float("inf")


def curve(fit: dict, ep: int, expert: bool) -> list[str]:
    rows = sorted((v for v in fit.values() if v["ep"] == ep), key=lambda v: v["batch_tokens"])
    out = []
    for v in rows:
        e = v["exp_median"] if expert else 1.0
        out.append(f"      - {{batch_tokens: {v['batch_tokens']}, token_imbalance: "
                   f"{v['tok_median']:.4f}, expert_imbalance: {e:.4f}, token_p10: "
                   f"{v['tok_p10']:.4f}, token_p90: {v['tok_p90']:.4f}}}")
    return out


def render(d: dict, digest: str) -> str:
    dec_tok = held_err(d["FIT"], d["HELD"], "tok")
    dec_exp = held_err(d["FIT"], d["HELD"], "exp")
    pf_tok = held_err(d["FIT_PREFILL_PROXY"], d["HELD_PREFILL_PROXY"], "tok")
    pf_exp = held_err(d["FIT_PREFILL_PROXY"], d["HELD_PREFILL_PROXY"], "exp")
    if dec_tok > MAX_HELD_ERR or dec_exp > MAX_HELD_ERR or pf_tok > MAX_HELD_ERR:
        raise SystemExit(f"held-out check failed: decode {dec_tok:.3f}/{dec_exp:.3f}, "
                         f"prefill token {pf_tok:.3f}")
    prefill_expert = pf_exp <= MAX_HELD_ERR
    deriv = f"scripts/derive_routing_profiles.py, output sha256 {digest}"
    lines = [
        "# Expert-parallel routing imbalance for DeepSeek-V4.1-Flash, from a measured routing capture.",
        "#",
        "# GENERATED by scripts/emit_routing_profiles.py from scripts/derive_routing_profiles.py's",
        "# output. Re-run both where the capture is present and commit the diff.",
        "kind: RoutingProfileSet",
        f"name: {SET_NAME}",
        "role: sensitivity",
        "caveats:",
        "- Tier 2 (a research group's capture, no paper). No tier-1 source measures DeepSeek-V4.1's",
        "  per-rank routed load, so the set is a sensitivity, applied only when a scenario names it.",
        "  The closest tier-1 figure, NVIDIA TensorRT-LLM tech blog 4 Table 1, measures DeepSeek-R1",
        "  decode at EP32 with EPLB off at max/mean 2.56, the same order as this set's EP16 2.10.",
        "- 'Prompts are enwik9 text (category text), not agentic coding: a coding workload uses",
        "  these curves only through a scenario pin''s fallback_category, which is recorded.'",
        "- Captured on B200 under a local vLLM fork; routing is a property of the model and the",
        "  traffic, not the chip, so a resolution on another part records the reuse.",
        "- Linear placement (expert e on rank e // (E / ep), vllm/config/parallel.py:192) with EPLB",
        "  off, recomputed from the captured expert ids at each width; the capture's own EP is 4.",
        "- Decode tokens only. The prefill curve is a PROXY, consecutive generated tokens of one",
        "  request, because prompt routes were not captured.",
        "- Checkpoint revision dba1be0a, against the catalog's 52544481.",
        "profiles:",
    ]
    for ep in (2, 4, 8, 16):
        lines += [
            "  - model: deepseek-v4.1-flash",
            f"    category: {CATEGORY}",
            "    phase: decode",
            "    placement: linear",
            f"    expert_parallel: {ep}",
            "    method: measured",
            "    provenance:",
            f'      source: "{SOURCE}"',
            f'      derivation: "{deriv}"',
            "      hardware: b200",
            f'      engine: "{ENGINE}"',
            "      requests: 40",
            "      tier: 2",
            "    rationale: >",
            "      Median over sampled steps of B tokens drawn at random from requests 0-39 (FIT),",
            "      a decode step mixing concurrent requests. Held out on requests 40-99: the largest",
            f"      FIT-to-HELD difference over every width and batch is {dec_tok:.1%} (token) and",
            f"      {dec_exp:.1%} (expert).",
            "    points:",
        ] + curve(d["FIT"], ep, True)
    for ep in (2, 4, 8, 16):
        exp_note = (f"expert {pf_exp:.1%}" if prefill_expert else
                    f"expert {pf_exp:.1%}, above the 10% tolerance, so the expert ratio is "
                    "written as 1 (the uniform-routing read)")
        lines += [
            "  - model: deepseek-v4.1-flash",
            f"    category: {CATEGORY}",
            "    phase: prefill",
            "    placement: linear",
            f"    expert_parallel: {ep}",
            "    method: assumed",
            "    provenance:",
            f'      source: "{SOURCE}"',
            f'      derivation: "{deriv}"',
            "      hardware: b200",
            f'      engine: "{ENGINE}"',
            "      requests: 40",
            "      tier: 2",
            "    rationale: >",
            "      A proxy, not a measurement: B consecutive generated tokens of one request stand",
            "      in for a B-token prefill chunk, since prompt routes were not captured. Tokens of",
            "      one request route alike, which is the effect a chunk has. Held out on requests",
            f"      40-99: largest FIT-to-HELD difference token {pf_tok:.1%}, {exp_note}.",
            "    points:",
        ] + curve(d["FIT_PREFILL_PROXY"], ep, prefill_expert)
    return "\n".join(lines) + "\n"


def main() -> None:
    args = [a for a in sys.argv[1:] if a != "--check"]
    raw = Path(args[0]).read_bytes()
    text = render(json.loads(raw), hashlib.sha256(raw).hexdigest())
    if "--check" in sys.argv:
        if TARGET.read_text() != text:
            raise SystemExit(f"{TARGET} is stale; re-run without --check")
        print("up to date")
        return
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(text)
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
